const { chromium } = require('playwright');
const fs = require('fs');
const THREE_PATH = '/tmp/claude-0/-home-claude/cb9526ed-9012-5cf4-ac72-246e7bebad80/scratchpad/npm/node_modules/three/build/three.min.js';
(async () => {
  const browser = await chromium.launch();
  const html = '<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover"></head><body>' + fs.readFileSync('/home/claude/quilt/quilt.html', 'utf8') + '</body></html>';
  const page = await browser.newPage({ viewport: { width: 1100, height: 760 }, colorScheme: 'light' });
  const logs = [];
  page.on('console', m => { if (m.type() === 'error') logs.push(m.text()); });
  page.on('pageerror', e => logs.push('pageerror: ' + e.message));
  await page.route('**/three.min.js', r => r.fulfill({ path: THREE_PATH, contentType: 'text/javascript' }));
  await page.route('https://fonts.googleapis.com/**', r => r.fulfill({ body: '', contentType: 'text/css' }));
  await page.route('http://x/', r => r.fulfill({ body: html, contentType: 'text/html' }));
  await page.goto('http://x/');
  await page.waitForFunction(() => document.getElementById('state').textContent.startsWith('At rest'), null, { timeout: 60000 });
  await page.waitForTimeout(500);
  await page.evaluate(() => window.scrollTo(0, 0)); await page.screenshot({ path: '/home/claude/quilt/an_sweep.png' });
  await page.waitForTimeout(2500);
  await page.evaluate(() => window.scrollTo(0, 0)); await page.screenshot({ path: '/home/claude/quilt/an_strain.png' });
  await page.selectOption('#field', 'clearance');
  await page.click('[data-cam="side"]'); await page.check('#ortho');
  await page.waitForTimeout(2000);
  await page.evaluate(() => window.scrollTo(0, 0)); await page.screenshot({ path: '/home/claude/quilt/an_clear.png' });
  await page.screenshot({ path: '/home/claude/quilt/an_card.png', clip: { x: 730, y: 0, width: 370, height: 760 } , fullPage: false}).catch(()=>{});
  await page.selectOption('#field', 'curvature'); await page.uncheck('#ortho'); await page.click('[data-cam="iso"]');
  await page.waitForTimeout(2000);
  await page.evaluate(() => window.scrollTo(0, 0)); await page.screenshot({ path: '/home/claude/quilt/an_curv.png' });
  const res = await page.evaluate(() => [...document.querySelectorAll('[id^="r-"]')].map(e => e.id + '=' + e.textContent).join('  '));
  console.log(res); console.log('errors', logs);
  await browser.close();
})();
