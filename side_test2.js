const { chromium } = require('playwright');
const fs = require('fs'), path = require('path');
const NM = '/tmp/claude-0/-home-claude/cb9526ed-9012-5cf4-ac72-246e7bebad80/scratchpad/npm/node_modules';
const MAP = [[/three@0\.183\.2\/(.*)$/, 'three'], [/three-mesh-bvh@0\.9\.14\/(.*)$/, 'three-mesh-bvh'], [/three-gpu-pathtracer@0\.0\.24\/(.*)$/, 'three-gpu-pathtracer']];
(async () => {
  const browser = await chromium.launch();
  const html = '<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"></head><body>' + fs.readFileSync('/home/claude/quilt/quilt.html', 'utf8') + '</body></html>';
  const page = await browser.newPage({ viewport: { width: 1300, height: 1000 } }); page.setDefaultTimeout(30000);
  const errs = []; page.on('pageerror', e => errs.push(e.message));
  await page.route('**/*', r => {
    const u = r.request().url();
    for (const [re, pkg] of MAP) { const m = u.match(re); if (m) return r.fulfill({ path: path.join(NM, pkg, m[1]), contentType: 'text/javascript' }); }
    if (u.startsWith('https://fonts.')) return r.fulfill({ body: '', contentType: 'text/css' });
    if (u.startsWith('http://x/assets/')) return r.fulfill({ path: '/home/claude/quilt/' + u.slice(9).split('#')[0] });
    if (u.startsWith('http://x/')) return r.fulfill({ body: html, contentType: 'text/html' });
    return r.abort();
  });
  await page.goto('http://x/#design');
  await page.waitForFunction(() => document.querySelectorAll('#dz-fabrics2 .fab').length > 0);
  await page.waitForTimeout(300);
  let q = await page.locator('#dz-quilt').boundingBox();
  const info = () => page.evaluate(() => ({ open: document.getElementById('dz-dialog').open, inSide: !!document.querySelector('#dz-sideparts #dz-block'), name: document.getElementById('dz-blockname').textContent }));
  await page.mouse.click(q.x + q.width * .5, q.y + q.height * .5); await page.waitForTimeout(200);
  console.log('tools hidden, click:', JSON.stringify(await info()));
  await page.click('#dz-done');
  await page.click('#dz-toggle'); await page.waitForTimeout(300);
  q = await page.locator('#dz-quilt').boundingBox();
  await page.mouse.click(q.x + q.width * .1, q.y + q.height * .1); await page.waitForTimeout(200);
  console.log('tools shown, click:', JSON.stringify(await info()));
  const bb = await page.locator('#dz-block').boundingBox();
  await page.mouse.click(bb.x + bb.width * .1, bb.y + bb.height * .1); await page.waitForTimeout(100);
  console.log('part info:', await page.textContent('#dz-parts-info'));
  await page.locator('#dz-sideparts #dz-fabrics2 .fab').nth(4).click(); await page.waitForTimeout(150);
  console.log('fabric now:', await page.evaluate(() => JSON.parse(localStorage.getItem('quilt-designer.v1')).blocks[0].fabrics.join(',')));
  await page.screenshot({ path: '/home/claude/quilt/side_mode.png' });
  await page.click('#dz-toggle'); await page.waitForTimeout(300);
  q = await page.locator('#dz-quilt').boundingBox();
  await page.mouse.click(q.x + q.width * .3, q.y + q.height * .3); await page.waitForTimeout(200);
  console.log('tools hidden again, click:', JSON.stringify(await info()));
  console.log('errors', errs);
  await browser.close();
})();
