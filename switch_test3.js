const { chromium } = require('playwright');
const fs = require('fs'), path = require('path');
const NM = '/tmp/claude-0/-home-claude/cb9526ed-9012-5cf4-ac72-246e7bebad80/scratchpad/npm/node_modules';
const MAP = [[/three@0\.183\.2\/(.*)$/, 'three'], [/three-mesh-bvh@0\.9\.14\/(.*)$/, 'three-mesh-bvh'], [/three-gpu-pathtracer@0\.0\.24\/(.*)$/, 'three-gpu-pathtracer']];
(async () => {
  const browser = await chromium.launch();
  const html = '<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"></head><body>' + fs.readFileSync('/home/claude/quilt/quilt.html', 'utf8') + '</body></html>';
  const page = await browser.newPage({ viewport: { width: 1300, height: 1000 } }); page.setDefaultTimeout(60000);
  const errs = []; page.on('pageerror', e => errs.push(e.message));
  await page.route('**/*', r => {
    const u = r.request().url();
    for (const [re, pkg] of MAP) { const m = u.match(re); if (m) return r.fulfill({ path: path.join(NM, pkg, m[1]), contentType: 'text/javascript' }); }
    if (u.startsWith('https://fonts.')) return r.fulfill({ body: '', contentType: 'text/css' });
    if (u.startsWith('http://x/assets/')) return r.fulfill({ path: '/home/claude/quilt/' + u.slice(9).split('#')[0] });
    if (u.startsWith('http://x/')) return r.fulfill({ body: html, contentType: 'text/html' });
    return r.abort();
  });
  await page.addInitScript(() => { if (!sessionStorage.getItem('x')) { sessionStorage.setItem('x', 1); localStorage.setItem('quilt-bed.v1', JSON.stringify({ key: 'br-solteiro', w: 880, l: 1880, drop: 300, tuck: true })); } });
  const cdp = await page.context().newCDPSession(page);
  const cdpShot = async f => { const r = { x: 0, y: 0, width: 1300, height: 1000 }; const { data } = await cdp.send('Page.captureScreenshot', { format: 'png', clip: { ...r, scale: 1 } }); require('fs').writeFileSync(f, Buffer.from(data, 'base64')); };
  await page.goto('http://x/');
  await page.waitForFunction(() => document.getElementById('atrest'));
  await page.evaluate(() => { const s = document.getElementById('atrest'); s.value = 'none'; s.dispatchEvent(new Event('change')); });
  await page.waitForTimeout(3000);
  const info = () => page.evaluate(() => { const s = document.getElementById('sim-side'), st = document.getElementById('stage').getBoundingClientRect(); return JSON.stringify({ docH: document.documentElement.scrollHeight, winH: innerHeight, pageScroll: scrollY, sideMax: s.style.maxHeight, sideScroll: s.scrollTop, sideScrollMax: s.scrollHeight - s.clientHeight, stageTop: Math.round(st.top), stageBottom: Math.round(st.bottom) }); });
  const tab = p => page.evaluate(p => document.querySelector(`[data-page="${p}"]`).click(), p);
  const info2 = () => page.evaluate(() => document.getElementById('intro').textContent.slice(0, 30) + ' | state ' + document.getElementById('state').textContent + ' | clock ' + document.getElementById('clock').textContent + ' | view ' + [...document.querySelectorAll('#views button')].find(b => b.getAttribute('aria-pressed') === 'true').textContent);
  await page.evaluate(() => { const e = document.getElementById('engine'); e.value = 'raster'; e.dispatchEvent(new Event('change')); document.querySelector('[data-view="render"]').click(); });
  await page.waitForTimeout(2500);
  console.log('sim     ', await info2()); await cdpShot('/home/claude/quilt/sw1.png');
  await tab('design'); await page.waitForTimeout(800);
  await page.evaluate(() => { const i = document.getElementById('dz-bmm2'); i.value = 380; i.dispatchEvent(new Event('change')); });
  await page.waitForTimeout(1500);
  await tab('sim'); await page.waitForTimeout(500);
  console.log('back 0.5s', await info2()); await cdpShot('/home/claude/quilt/sw2.png');
  await page.waitForTimeout(6000);
  console.log('back 6s ', await info2()); await cdpShot('/home/claude/quilt/sw3.png');
  await page.evaluate(() => document.querySelector('[data-view="render"]').click()); await page.waitForTimeout(2500);
  console.log('render  ', await page.evaluate(() => document.getElementById('rstat').textContent));
  await tab('cut'); await page.waitForTimeout(1500); await tab('sim'); await page.waitForTimeout(2500);
  console.log('render after cut->sim', await page.evaluate(() => document.getElementById('rstat').textContent + ' | canvas ' + document.getElementById('view').width + 'x' + document.getElementById('view').height));
  console.log('cut->sim', await info2()); await cdpShot('/home/claude/quilt/sw4.png');
  console.log('errors', errs);
  await browser.close();
})();
